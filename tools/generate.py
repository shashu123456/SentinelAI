#!/usr/bin/env python3
"""Scaffolders for SentinelAI — generate code that already follows conventions.

    python tools/generate.py route webhooks
    python tools/generate.py page ReportBuilder
    python tools/generate.py component SeverityBadge
    python tools/generate.py plugin saml_login
    python tools/generate.py fixture findings

Every generator:

* uses the same layout, imports, and docstring style as the existing code;
* emits a matching test file so `make test` covers new code from day one;
* refuses to overwrite files unless ``--force`` is passed;
* supports ``--dry-run`` so you can preview the output.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
BACKEND = REPO_ROOT / "backend"
FRONTEND = REPO_ROOT / "frontend"

RESET = "\033[0m" if sys.stdout.isatty() else ""
GREEN = "\033[92m" if sys.stdout.isatty() else ""
DIM = "\033[2m" if sys.stdout.isatty() else ""
RED = "\033[91m" if sys.stdout.isatty() else ""
# ASCII markers: legacy Windows consoles cannot encode ✔ / ✖.
OK = "[ok]"
ERR = "[err]"


def snake(name: str) -> str:
    name = re.sub(r"[\s\-]+", "_", name.strip())
    name = re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()
    return re.sub(r"_+", "_", name)


def pascal(name: str) -> str:
    return "".join(part.capitalize() for part in snake(name).split("_") if part)


def title(name: str) -> str:
    return " ".join(part.capitalize() for part in snake(name).split("_"))


