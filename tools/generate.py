# ── Generator implementations ────────────────────────────────────────


def gen_route(name: str, force: bool, dry: bool) -> int:
    slug = snake(name)
    pascal_name = pascal(name)
    files = {
        BACKEND / "app" / "api" / "routes" / f"{slug}.py": ROUTE_TEMPLATE,
        BACKEND / "tests" / f"test_{slug}.py": ROUTE_TEST_TEMPLATE,
    }
    rendered = {
        path: template.format(slug=slug, pascal=pascal_name, snake=slug, title=title(name))
        for path, template in files.items()
    }
    code = write(rendered, force, dry)
    if code == 0 and not dry:
        print(
            f"\n{DIM}Register the router by adding to backend/app/main.py:{RESET}\n"
            f"  from app.api.routes import {slug}\n"
            f"  app.include_router({slug}.router)\n"
        )
    return code


def gen_page(name: str, force: bool, dry: bool) -> int:
    slug = snake(name)
    pascal_name = pascal(name)
    base = FRONTEND / "src" / "pages"
    rendered = {
        base / f"{pascal_name}.jsx": PAGE_TEMPLATE.format(
            slug=slug, pascal=pascal_name, title=title(name)
        ),
        base / f"{pascal_name}.css": PAGE_CSS_TEMPLATE.format(slug=slug),
        base / f"{pascal_name}.test.jsx": PAGE_TEST_TEMPLATE.format(
            pascal=pascal_name, title=title(name)
        ),
    }
    code = write(rendered, force, dry)
    if code == 0 and not dry:
        print(
            f"\n{DIM}Add the route in frontend/src/App.jsx:{RESET}\n"
            f'  <Route path="/{slug}" element={{<{pascal_name} />}} />\n'
        )
    return code


def gen_component(name: str, force: bool, dry: bool) -> int:
    pascal_name = pascal(name)
    slug = snake(name).replace("_", "-")
    base = FRONTEND / "src" / "components"
    rendered = {
        base / f"{pascal_name}.jsx": COMPONENT_TEMPLATE.format(pascal=pascal_name, slug=slug),
        base / f"{pascal_name}.test.jsx": COMPONENT_TEST_TEMPLATE.format(pascal=pascal_name),
    }
    return write(rendered, force, dry)


def gen_plugin(name: str, force: bool, dry: bool) -> int:
    slug = snake(name)
    pascal_name = pascal(name)
    plugin_path = BACKEND / "app" / "core" / "plugins" / f"{slug}_plugin.py"
    rendered = {
        plugin_path: PLUGIN_TEMPLATE.format(slug=slug, pascal=pascal_name, title=title(name)),
        BACKEND / "tests" / f"test_{slug}_plugin.py": PLUGIN_TEST_TEMPLATE.format(
            slug=slug, pascal=pascal_name, module_path="app.core.plugins." + f"{slug}_plugin"
        ),
    }
    return write(rendered, force, dry)


def gen_fixture(name: str, force: bool, dry: bool) -> int:
    slug = snake(name)
    rendered = {
        BACKEND / "tests" / "helpers" / f"{slug}.py": FIXTURE_TEMPLATE.format(
            slug=slug, snake=slug, title=title(name)
        )
    }
    return write(rendered, force, dry)


def write(rendered: dict[Path, str], force: bool, dry: bool) -> int:
    existing = [path for path in rendered if path.exists()]
    if existing and not force:
        for path in existing:
            print(
                f"{RED}{ERR}{RESET} exists: {relative(path)} (use --force to overwrite)",
                file=sys.stderr,
            )
        return 1

    for path, content in rendered.items():
        if dry:
            print(f"{DIM}--- {relative(path)} ---{RESET}")
            print(content.rstrip() + "\n")
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"{GREEN}{OK}{RESET} created {relative(path)}")
    return 0


def relative(path: Path) -> str:
    try:
        return str(path.relative_to(REPO_ROOT))
    except ValueError:
        return str(path)


# ── CLI ──────────────────────────────────────────────────────────────

GENERATORS = {
    "route": (gen_route, "Backend API router + tests"),
    "page": (gen_page, "Frontend page + CSS + tests"),
    "component": (gen_component, "Frontend component + tests"),
    "plugin": (gen_plugin, "Scanner plugin + tests"),
    "fixture": (gen_fixture, "Reusable test fixture module"),
}


def usage() -> None:
    print(
        """
SentinelAI code generators

  python tools/generate.py <kind> <Name> [--force] [--dry-run]

Kinds:
  route      backend/app/api/routes/<name>.py + tests
  page       frontend/src/pages/<Name>.jsx (+ css, test)
  component  frontend/src/components/<Name>.jsx (+ test)
  plugin     backend/app/core/plugins/<name>_plugin.py (+ test)
  fixture    backend/tests/helpers/<name>.py

Examples:
  python tools/generate.py route webhooks
  python tools/generate.py page ReportBuilder --dry-run
  python tools/generate.py component SeverityBadge
""".rstrip()
    )


def main(argv: list[str]) -> int:
    if any(a in ("-h", "--help", "help") for a in argv):
        usage()
        return 0

    args = [a for a in argv if not a.startswith("-")]
    flags = {a for a in argv if a.startswith("-")}

    if not args:
        usage()
        return 1

    kind = args[0]
    if kind not in GENERATORS:
        print(f"Unknown generator '{kind}'. Try --help.", file=sys.stderr)
        return 2
    if len(args) < 2:
        print(f"Missing name. Example: python tools/generate.py {kind} Example", file=sys.stderr)
        return 2

    func = GENERATORS[kind][0]
    return func(args[1], force="--force" in flags, dry="--dry-run" in flags)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
