PAGE_TEMPLATE = """import {{ useEffect, useState }} from 'react';

import {{ request }} from '../services/api';
import './{pascal}.css';

export default function {pascal}() {{
  const [items, setItems] = useState([]);
  const [error, setError] = useState(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {{
    let cancelled = false;

    async function load() {{
      try {{
        const data = await request('/{slug}/');
        if (!cancelled) setItems(Array.isArray(data) ? data : []);
      }} catch (err) {{
        if (!cancelled) setError(err.message || 'Failed to load');
      }} finally {{
        if (!cancelled) setLoading(false);
      }}
    }}

    load();
    return () => {{
      cancelled = true;
    }};
  }}, []);

  return (
    <section className="page-{slug}">
      <header className="page-{slug}__header">
        <h1>{title}</h1>
        <p>Generated by <code>tools/generate.py page</code> - replace with real content.</p>
      </header>

      {{loading && <p>Loading...</p>}}
      {{error && <p role="alert">{{error}}</p>}}

      {{!loading && !error && items.length === 0 && <p>Nothing here yet.</p>}}

      <ul>
        {{items.map((item) => (
          <li key={{item.id}}>{{ item.name }}</li>
        ))}}
      </ul>
    </section>
  );
}}
"""

